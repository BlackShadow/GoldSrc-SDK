void ApplyMemoryInitializations( void* pMemory, size_t nSize )
{
#if defined( _WIN32 )
	if ( !pMemory )
		return;

	static bool bDebugger = IsDebuggerPresent() != FALSE;
	static bool bCheckedCommandLine;
	static bool bRandomize;
	static bool bInitialize = true;
	static unsigned int nextRandom;
	if ( !bCheckedCommandLine )
	{
		bCheckedCommandLine = true;
		const char* pCommandLine = GetCommandLineA();
		if ( pCommandLine )
		{
			char commandLine[512];
			strncpy( commandLine, pCommandLine, sizeof( commandLine ) - 1 );
			commandLine[sizeof( commandLine ) - 1] = '\0';
			_strupr( commandLine );
			bRandomize = strstr( commandLine, "-RANDOMIZEMEMORY" ) != NULL;
			if ( strstr( commandLine, "-NOINITMEMORY" ) )
				bInitialize = false;
		}
	}

	if ( !bInitialize )
		return;

	unsigned char* pBytes = (unsigned char*)pMemory;
	if ( bRandomize )
	{
		for ( size_t i = 0; i < nSize; ++i )
			pBytes[i] = s_RandomMemory[( nextRandom++ ) & ( sizeof( s_RandomMemory ) - 1 )];
	}
	else if ( bDebugger )
	{
		static const unsigned char pattern[] = { 0xee, 0xff, 0xee, 0xff };
		for ( size_t i = 0; i < nSize; ++i )
			pBytes[i] = pattern[i % sizeof( pattern )];
	}
#else
	(void)pMemory;
	(void)nSize;
#endif
}

size_t CalcHeapUsed()
{
#if defined( _WIN32 )
	return g_pMemAlloc->GetMemoryUsed();
#else
	return 0;
#endif
}
