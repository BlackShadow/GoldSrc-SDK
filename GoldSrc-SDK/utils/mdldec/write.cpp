// write.cpp -- QC script export

#include "mdldec.h"

#include <stdio.h>
#include <string.h>

void CMDLDecompiler::WriteQC()
{
	char filename[264];
	// guard: output path (command line) plus a name from the file can exceed filename[264]; the
	// native sprintf overruns it. Take the existing "cannot write" path when it does not fit.
	int written = _snprintf( filename, sizeof( filename ), "%s%s.qc", m_szOutputPath, m_szModelName );
	filename[sizeof( filename ) - 1] = 0;
	if ( written < 0 || written >= (int)sizeof( filename ) )
	{
		Log( 2, "ERROR: Cannot write %s\r\n", filename );
		return;
	}
	m_pQCFile = fopen( filename, "w" );
	if ( !m_pQCFile )
	{
		Log( 2, "ERROR: Cannot write %s\r\n", filename );
		return;
	}

	fprintf( m_pQCFile, "/*\n" );
	fprintf( m_pQCFile, "==============================================================================\n\n" );
	fprintf( m_pQCFile, "QC script generated by Half-Life MDL Decompiler %s \n", "1.2" );
	fprintf( m_pQCFile, "2003, Kratisto. Based on code from Valve's HL SDK.\n\n" );
	fprintf( m_pQCFile, "%s.mdl\n\n", m_szModelName );
	fprintf( m_pQCFile, "Original internal name:\n" );
	fprintf( m_pQCFile, "\"%s\"\n\n", m_pStudioHeader->name );
	fprintf( m_pQCFile, "==============================================================================\n" );
	fprintf( m_pQCFile, "*/\n\n" );
	fprintf( m_pQCFile, "$modelname \"%s.mdl\"\n", m_szModelName );
	fprintf( m_pQCFile, "$cd \".\\\"\n" );
	fprintf( m_pQCFile, "$cdtexture \".\\\"\n" );
	fprintf( m_pQCFile, "$scale 1.0\n" );
	fprintf( m_pQCFile, "$cliptotextures\n" );
	fprintf( m_pQCFile, "\n" );
	if ( !m_pStudioHeader->numtextures )
		fprintf( m_pQCFile, "$externaltextures\n" );
	if ( m_pStudioHeader->flags )
	{
		fprintf( m_pQCFile, "$flags %i\n", m_pStudioHeader->flags );
		Log( 1, "WARNING: This model uses the $flags keyword set to %i\r\n", m_pStudioHeader->flags );
	}
	fprintf( m_pQCFile, "\n" );
	fprintf( m_pQCFile, "$bbox %f %f %f",
		FloatForPrint( m_pStudioHeader->min[0] ), FloatForPrint( m_pStudioHeader->min[1] ),
		FloatForPrint( m_pStudioHeader->min[2] ) );
	fprintf( m_pQCFile, " %f %f %f\n",
		FloatForPrint( m_pStudioHeader->max[0] ), FloatForPrint( m_pStudioHeader->max[1] ),
		FloatForPrint( m_pStudioHeader->max[2] ) );
	fprintf( m_pQCFile, "$cbox %f %f %f",
		FloatForPrint( m_pStudioHeader->bbmin[0] ), FloatForPrint( m_pStudioHeader->bbmin[1] ),
		FloatForPrint( m_pStudioHeader->bbmin[2] ) );
	fprintf( m_pQCFile, " %f %f %f\n",
		FloatForPrint( m_pStudioHeader->bbmax[0] ), FloatForPrint( m_pStudioHeader->bbmax[1] ),
		FloatForPrint( m_pStudioHeader->bbmax[2] ) );
	fprintf( m_pQCFile, "$eyeposition %f %f %f\n",
		FloatForPrint( m_pStudioHeader->eyeposition[0] ), FloatForPrint( m_pStudioHeader->eyeposition[1] ),
		FloatForPrint( m_pStudioHeader->eyeposition[2] ) );
	fprintf( m_pQCFile, "\n" );

	WriteBodyParts();
	WriteTextureModes();
	WriteTextureGroups();
	WriteAttachments();
	WriteControllers();
	WriteHitboxes();
	WriteQCSequences();
	fprintf( m_pQCFile, "\n// End of QC script.\n" );
	Log( 0, "QC Script: %s\r\n", filename );
	fclose( m_pQCFile );
}

void CMDLDecompiler::WriteTextureModes()
{
	studiohdr_t* header = m_pStudioHeader;
	if ( !header->numtextures )
		header = m_pTextureHeader;

	mstudiotexture_t* textures = (mstudiotexture_t*)( (byte*)header + header->textureindex );
	const byte* texBase = (const byte*)header;
	const byte* texEnd = texBase + ( m_pStudioHeader->numtextures ? m_nModelSize : m_nTextureSize );
	for ( int i = 0; i < header->numtextures; i++ )
	{
		// guard: numtextures/textureindex come from the file; stop when the texture
		// descriptor leaves its loaded buffer.
		if ( (const byte*)&textures[i] < texBase || (const byte*)&textures[i + 1] > texEnd )
			break;
		mstudiotexture_t* texture = &textures[i];
		switch ( texture->flags )
		{
		case 0:
		case STUDIO_NF_FLATSHADE:
		case STUDIO_NF_CHROME:
		case STUDIO_NF_FLATSHADE | STUDIO_NF_CHROME:
		case STUDIO_NF_FULLBRIGHT:
			break;
		case STUDIO_NF_ADDITIVE:
			fprintf( m_pQCFile, "$texrendermode \"%s\" \"additive\" \n", texture->name );
			break;
		case STUDIO_NF_MASKED:
			fprintf( m_pQCFile, "$texrendermode \"%s\" \"masked\" \n", texture->name );
			break;
		case STUDIO_NF_ADDITIVE | STUDIO_NF_MASKED:
			fprintf( m_pQCFile, "$texrendermode \"%s\" \"masked\" \n", texture->name );
			fprintf( m_pQCFile, "$texrendermode \"%s\" \"additive\" \n", texture->name );
			break;
		default:
			Log( 1, "WARNING: Texture %s has an unknown render mode flags value ( %i )\r\n",
				texture->name, texture->flags );
			break;
		}
	}
}

void CMDLDecompiler::WriteTextureGroups()
{
	studiohdr_t* header = m_pStudioHeader;
	if ( !header->numtextures )
		header = m_pTextureHeader;
	if ( header->numskinfamilies <= 1 )
		return;

	fprintf( m_pQCFile, "\n// %i skin families\n", header->numskinfamilies );
	fprintf( m_pQCFile, "$texturegroup skinfamilies \n{\n" );
	short* skins = (short*)( (byte*)header + header->skinindex );
	mstudiotexture_t* textures = (mstudiotexture_t*)( (byte*)header + header->textureindex );
	const byte* texBase = (const byte*)header;
	const byte* texEnd = texBase + ( m_pStudioHeader->numtextures ? m_nModelSize : m_nTextureSize );
	for ( int i = 0; i < header->numskinfamilies; i++ )
	{
		fprintf( m_pQCFile, "{" );
		for ( int j = 0; j < header->numskinref; j++ )
		{
			// guard: numskinfamilies/numskinref/skinindex come from the file; skip a
			// skin reference that lies outside the skins array's loaded buffer.
			if ( (const byte*)&skins[i * header->numskinref + j] < texBase
				|| (const byte*)&skins[i * header->numskinref + j + 1] > texEnd )
				continue;
			short skin = skins[i * header->numskinref + j];
			for ( int k = 0; k < header->numskinfamilies; k++ )
			{
				if ( (const byte*)&skins[k * header->numskinref + j] < texBase
					|| (const byte*)&skins[k * header->numskinref + j + 1] > texEnd )
					continue;
				if ( skin != skins[k * header->numskinref + j] )
				{
					// guard: skin indexes the textures array.
					if ( skin >= 0 && skin < header->numtextures
						&& (const byte*)&textures[skin + 1] <= texEnd )
						fprintf( m_pQCFile, " \"%s\" ", textures[skin].name );
					break;
				}
			}
		}
		fprintf( m_pQCFile, "}\n" );
	}
	fprintf( m_pQCFile, "}\n" );
}

void CMDLDecompiler::WriteBodyParts()
{
	fprintf( m_pQCFile, "\n//reference mesh(es)\n" );
	mstudiobodyparts_t* bodyparts =
		(mstudiobodyparts_t*)( m_pModelData + m_pStudioHeader->bodypartindex );
	const byte* bufEnd = m_pModelData + m_nModelSize;
	for ( int i = 0; i < m_pStudioHeader->numbodyparts; i++ )
	{
		// guard: bodypartindex/numbodyparts come from the file; stop when the bodypart
		// descriptor leaves the loaded buffer.
		if ( (const byte*)&bodyparts[i] < m_pModelData || (const byte*)&bodyparts[i + 1] > bufEnd )
			break;
		mstudiobodyparts_t* bodypart = &bodyparts[i];
		mstudiomodel_t* models = (mstudiomodel_t*)( m_pModelData + bodypart->modelindex );
		if ( bodypart->nummodels == 1 )
		{
			// guard: modelindex comes from the file; skip a model outside the buffer
			// (ExtractFileBase would otherwise read and write its name field there).
			if ( (const byte*)models >= m_pModelData && (const byte*)&models[1] <= bufEnd )
			{
				ExtractFileBase( models->name, models->name, sizeof( models->name ) );
				fprintf( m_pQCFile, "$body \"%s\" \"%s\"\n\n", bodypart->name, models->name );
			}
		}
		else
		{
			fprintf( m_pQCFile, "$bodygroup \"%s\"\n", bodypart->name );
			fprintf( m_pQCFile, "{\n" );
			for ( int j = 0; j < bodypart->nummodels; j++ )
			{
				// guard: nummodels/modelindex come from the file; stop when the model
				// descriptor leaves the loaded buffer.
				if ( (const byte*)&models[j] < m_pModelData || (const byte*)&models[j + 1] > bufEnd )
					break;
				if ( strncmp( models[j].name, "blank", 5 ) == 0 )
				{
					fprintf( m_pQCFile, "blank\n" );
				}
				else
				{
					ExtractFileBase( models[j].name, models[j].name, sizeof( models[j].name ) );
					fprintf( m_pQCFile, "studio \"%s\"\n", models[j].name );
				}
			}
			fprintf( m_pQCFile, "}\n\n" );
		}
	}
}

void CMDLDecompiler::WriteAttachments()
{
	if ( m_pStudioHeader->numattachments <= 0 )
		return;

	fprintf( m_pQCFile, "\n// %i attachment(s)\n", m_pStudioHeader->numattachments );
	mstudioattachment_t* attachments =
		(mstudioattachment_t*)( m_pModelData + m_pStudioHeader->attachmentindex );
	mstudiobone_t* bones = (mstudiobone_t*)( m_pModelData + m_pStudioHeader->boneindex );
	const byte* bufEnd = m_pModelData + m_nModelSize;
	for ( int i = 0; i < m_pStudioHeader->numattachments; i++ )
	{
		// guard: attachmentindex/numattachments come from the file; stop when the
		// attachment descriptor leaves the loaded buffer.
		if ( (const byte*)&attachments[i] < m_pModelData || (const byte*)&attachments[i + 1] > bufEnd )
			break;
		mstudioattachment_t* attachment = &attachments[i];
		// guard: attachment->bone indexes the bones array; an out-of-range index would
		// read a bone name outside it.
		const char* boneName = ( (unsigned)attachment->bone < (unsigned)m_pStudioHeader->numbones )
			? bones[attachment->bone].name : "";
		fprintf( m_pQCFile, "$attachment %i \"%s\" %f %f %f\n", i,
			boneName, FloatForPrint( attachment->org[0] ),
			FloatForPrint( attachment->org[1] ), FloatForPrint( attachment->org[2] ) );
	}
}

void CMDLDecompiler::WriteControllers()
{
	if ( m_pStudioHeader->numbonecontrollers <= 0 )
		return;

	fprintf( m_pQCFile, "\n// %i bone controller(s)\n", m_pStudioHeader->numbonecontrollers );
	mstudiobonecontroller_t* controllers =
		(mstudiobonecontroller_t*)( m_pModelData + m_pStudioHeader->bonecontrollerindex );
	mstudiobone_t* bones = (mstudiobone_t*)( m_pModelData + m_pStudioHeader->boneindex );
	const byte* bufEnd = m_pModelData + m_nModelSize;
	for ( int i = 0; i < m_pStudioHeader->numbonecontrollers; i++ )
	{
		// guard: bonecontrollerindex/numbonecontrollers come from the file; stop when the
		// controller descriptor leaves the loaded buffer.
		if ( (const byte*)&controllers[i] < m_pModelData || (const byte*)&controllers[i + 1] > bufEnd )
			break;
		char motion[8];
		mstudiobonecontroller_t* controller = &controllers[i];
		GetMotionTypeName( controller->type & ~STUDIO_RLOOP, motion, false );
		// guard: controller->bone indexes the bones array.
		const char* boneName = ( (unsigned)controller->bone < (unsigned)m_pStudioHeader->numbones )
			? bones[controller->bone].name : "";
		fprintf( m_pQCFile, "$controller %i \"%s\" %s %f %f\n", controller->index,
			boneName, motion, FloatForPrint( controller->start ), FloatForPrint( controller->end ) );
	}
}

void CMDLDecompiler::WriteHitboxes()
{
	if ( m_pStudioHeader->numhitboxes <= 0 )
		return;

	fprintf( m_pQCFile, "\n// %i hit box(es)\n", m_pStudioHeader->numhitboxes );
	mstudiobbox_t* hitboxes = (mstudiobbox_t*)( m_pModelData + m_pStudioHeader->hitboxindex );
	mstudiobone_t* bones = (mstudiobone_t*)( m_pModelData + m_pStudioHeader->boneindex );
	const byte* bufEnd = m_pModelData + m_nModelSize;
	for ( int i = 0; i < m_pStudioHeader->numhitboxes; i++ )
	{
		// guard: hitboxindex/numhitboxes come from the file; stop when the hitbox
		// descriptor leaves the loaded buffer.
		if ( (const byte*)&hitboxes[i] < m_pModelData || (const byte*)&hitboxes[i + 1] > bufEnd )
			break;
		mstudiobbox_t* box = &hitboxes[i];
		// guard: box->bone indexes the bones array.
		const char* boneName = ( (unsigned)box->bone < (unsigned)m_pStudioHeader->numbones )
			? bones[box->bone].name : "";
		fprintf( m_pQCFile, "$hbox %i \"%s\" %f %f %f %f %f %f\n", box->group, boneName,
			FloatForPrint( box->bbmin[0] ), FloatForPrint( box->bbmin[1] ), FloatForPrint( box->bbmin[2] ),
			FloatForPrint( box->bbmax[0] ), FloatForPrint( box->bbmax[1] ), FloatForPrint( box->bbmax[2] ) );
	}
}

void CMDLDecompiler::WriteQCSequences()
{
	if ( m_pStudioHeader->numseqgroups > 1 )
		fprintf( m_pQCFile, "\n$sequencegroupsize 64\n" );
	if ( m_pStudioHeader->numseq > 0 )
		fprintf( m_pQCFile, "\n// %i animation sequence(s)\n", m_pStudioHeader->numseq );

	mstudioseqdesc_t* sequences = (mstudioseqdesc_t*)( m_pModelData + m_pStudioHeader->seqindex );
	const byte* bufEnd = m_pModelData + m_nModelSize;
	for ( int i = 0; i < m_pStudioHeader->numseq; i++ )
	{
		// guard: seqindex/numseq come from the file; stop when the seqdesc would be read
		// past the loaded buffer.
		if ( (const byte*)&sequences[i] < m_pModelData || (const byte*)&sequences[i + 1] > bufEnd )
			break;
		// guard: the native's char motion[32] overflows when GetMotionTypeName gets all 15
		// motion bits (45 characters written); size the buffer to hold the largest output.
		char motion[64];
		mstudioseqdesc_t* sequence = &sequences[i];
		// guard: numblends/seqgroup/animindex come from the file; bound the blend count
		// so a blend reference cannot describe animation past its loaded buffer
		// (doctor.mdl seq 6 claims 387,389,207 blends with an out-of-range seqgroup).
		int nblends = sequence->numblends;
		if ( sequence->seqgroup < 0 || sequence->seqgroup >= MAX_SEQUENCE_FILES )
		{
			nblends = 0;
		}
		else
		{
			int animBufSize = sequence->seqgroup != 0
				? m_nSequenceSize[sequence->seqgroup] : m_nModelSize;
			int stride = m_pStudioHeader->numbones * (int)sizeof( mstudioanim_t );
			if ( stride <= 0 )
				nblends = 0;
			else if ( nblends > animBufSize / stride )
				nblends = animBufSize / stride;
		}
		fprintf( m_pQCFile, "$sequence \"%s\" ", sequence->label );
		if ( nblends > 1 )
		{
			if ( nblends > 2 )
				fprintf( m_pQCFile, "{\n" );
			for ( int j = 0; j < nblends; j++ )
			{
				if ( nblends > 2 )
					fprintf( m_pQCFile, "          " );
				fprintf( m_pQCFile, "\"%s_blend%i\" ", sequence->label, j + 1 );
				if ( nblends > 2 )
					fprintf( m_pQCFile, "\n" );
			}
			if ( nblends > 2 )
				fprintf( m_pQCFile, "          " );
			GetMotionTypeName( sequence->blendtype[0], motion, false );
			fprintf( m_pQCFile, "blend %s %.0f %.0f", motion,
				FloatForPrint( sequence->blendstart[0] ), FloatForPrint( sequence->blendend[0] ) );
		}
		else
		{
			fprintf( m_pQCFile, "\"%s\"", sequence->label );
		}
		if ( sequence->motiontype )
		{
			GetMotionTypeName( sequence->motiontype, motion, true );
			fprintf( m_pQCFile, "%s ", motion );
		}
		else
		{
			fprintf( m_pQCFile, " " );
		}
		fprintf( m_pQCFile, "fps %.0f ", FloatForPrint( sequence->fps ) );
		if ( sequence->flags == STUDIO_LOOPING )
			fprintf( m_pQCFile, "loop " );
		if ( sequence->activity )
		{
			if ( GetActivityName( sequence->activity, motion ) )
			{
				fprintf( m_pQCFile, "%s %i ", motion, sequence->actweight );
			}
			else
			{
				Log( 1, "WARNING: Sequence %s has a custom activity flag (ACT_%i %i).\r\n",
					sequence->label, sequence->activity, sequence->actweight );
				fprintf( m_pQCFile, "ACT_%i %i ", sequence->activity, sequence->actweight );
			}
		}
		if ( sequence->entrynode && sequence->exitnode )
		{
			Log( 1, "WARNING: Sequence %s uses transition nodes.\r\n", sequence->label );
			if ( sequence->entrynode == sequence->exitnode )
			{
				fprintf( m_pQCFile, "node %i ", sequence->entrynode );
			}
			else if ( sequence->nodeflags )
			{
				fprintf( m_pQCFile, "rtransition %i %i ", sequence->entrynode, sequence->exitnode );
			}
			else
			{
				fprintf( m_pQCFile, "transition %i %i ", sequence->entrynode, sequence->exitnode );
			}
		}
		if ( sequence->numevents > 2 )
			fprintf( m_pQCFile, "{\n " );
		mstudioevent_t* events = (mstudioevent_t*)( m_pModelData + sequence->eventindex );
		for ( int j = 0; j < sequence->numevents; j++ )
		{
			// guard: numevents/eventindex come from the file; doctor.mdl seq 3 claims
			// 1,125,368,083 events at eventindex 0, so events[j] walks off the loaded
			// buffer into unmapped memory and the native crashes (0xC0000005). Stop at
			// the buffer edge.
			if ( (const byte*)&events[j] < m_pModelData || (const byte*)&events[j + 1] > bufEnd )
				break;
			if ( sequence->numevents > 2 )
			{
				if ( nblends > 2 )
					fprintf( m_pQCFile, "          " );
				else
					fprintf( m_pQCFile, " " );
			}
			fprintf( m_pQCFile, "{ event %i %i", events[j].event, events[j].frame );
			if ( strlen( events[j].options ) )
				fprintf( m_pQCFile, " \"%s\"", events[j].options );
			fprintf( m_pQCFile, " } " );
			if ( sequence->numevents > 2 )
				fprintf( m_pQCFile, "\n " );
		}
		if ( sequence->numevents > 2 )
			fprintf( m_pQCFile, "}" );
		fprintf( m_pQCFile, "\n" );
		if ( nblends > 2 )
			fprintf( m_pQCFile, "}\n" );
		if ( sequence->numpivots > 0 )
			Log( 1, "WARNING: Sequence %s uses %i foot pivots, feature not supported.\r\n",
				sequence->label, sequence->numpivots );
	}
}

